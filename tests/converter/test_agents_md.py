"""--agents-md: an AGENTS.md at the tree root that points AI coding agents at
the chart's own docs, at the chart revision the tree deploys. Off by default,
never overwrites a hand-written one, and --upgrade keeps it on."""
import subprocess
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]  # the universal-chart checkout
CMD = [sys.executable, str(REPO / "gitops-factory" / "convert_to_universal_chart.py")]
MARKER = "Generated by convert_to_universal_chart.py (--agents-md)"


def deployment(name, ns):
    return {"apiVersion": "apps/v1", "kind": "Deployment", "metadata": {"name": name, "namespace": ns},
            "spec": {"selector": {"matchLabels": {"app": name}}, "template": {
                "metadata": {"labels": {"app": name}},
                "spec": {"containers": [{"name": name, "image": f"registry.example.com/{name}:1.0"}]}}}}


def convert(tmp_path, *flags, out=None):
    src = tmp_path / "in" / "shop-dev"
    if not src.is_dir():
        src.mkdir(parents=True)
        (src / "api.yaml").write_text(yaml.safe_dump(deployment("api", "shop-dev")), encoding="utf-8")
    out = out or tmp_path / "out"
    r = subprocess.run([*CMD, "--input", str(tmp_path / "in"), "--output", str(out), "--skip-verify", *flags],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    assert r.returncode == 0, r.stdout[-3000:] + r.stderr[-3000:]
    return out


def test_off_by_default(tmp_path):
    out = convert(tmp_path)
    assert not (out / "AGENTS.md").exists()


def test_written_with_the_chart_it_deploys(tmp_path):
    out = convert(tmp_path, "--agents-md", "--argocd-manifests", "true",
                  "--chart-repo-url", "ssh://git@bitbucket.example.com:7999/plat/universal-chart.git",
                  "--chart-revision", "v4.0.0")
    text = (out / "AGENTS.md").read_text(encoding="utf-8")
    assert MARKER in text
    assert "rootApplicationSet.yaml" in text
    # The fallback for a tree without wiring is filled in; no placeholder is left.
    assert "ssh://git@bitbucket.example.com:7999/plat/universal-chart.git" in text
    assert "`v4.0.0`" in text
    assert "__CHART_" not in text
    # What it tells the agent to read from rootApplicationSet.yaml is there.
    appset = yaml.safe_load((out / "rootApplicationSet.yaml").read_text(encoding="utf-8"))
    src = appset["spec"]["template"]["spec"]["sources"][0]
    assert src["repoURL"] == "ssh://git@bitbucket.example.com:7999/plat/universal-chart.git"
    assert src["targetRevision"] == "v4.0.0"


def test_hand_written_agents_md_is_kept(tmp_path):
    out = tmp_path / "out"
    out.mkdir()
    (out / "AGENTS.md").write_text("# our own rules\n", encoding="utf-8")
    convert(tmp_path, "--agents-md", out=out)
    assert (out / "AGENTS.md").read_text(encoding="utf-8") == "# our own rules\n"


def test_generated_one_is_refreshed(tmp_path):
    out = tmp_path / "out"
    out.mkdir()
    (out / "AGENTS.md").write_text(f"old text\n<!-- {MARKER} -->\n", encoding="utf-8")
    convert(tmp_path, "--agents-md", "--chart-revision", "v4.1.0", out=out)
    text = (out / "AGENTS.md").read_text(encoding="utf-8")
    assert "old text" not in text and "`v4.1.0`" in text


def upgrade(tree, out):
    r = subprocess.run([*CMD, "--upgrade", str(tree), "--upgrade-offline", "--upgrade-chart", str(REPO),
                        "-o", str(out), "--skip-verify"],
                       capture_output=True, text=True, encoding="utf-8", errors="replace")
    assert r.returncode == 0, r.stdout[-3000:] + r.stderr[-3000:]
    return r


def test_upgrade_keeps_it(tmp_path):
    tree = convert(tmp_path, "--agents-md", "--argocd-manifests", "true")
    r = upgrade(tree, tmp_path / "up")
    assert "agents-md = True" in r.stdout + r.stderr
    assert MARKER in (tmp_path / "up" / "AGENTS.md").read_text(encoding="utf-8")


def test_upgrade_does_not_add_it_to_a_tree_without_one(tmp_path):
    tree = convert(tmp_path, "--argocd-manifests", "true")
    upgrade(tree, tmp_path / "up")
    assert not (tmp_path / "up" / "AGENTS.md").exists()
